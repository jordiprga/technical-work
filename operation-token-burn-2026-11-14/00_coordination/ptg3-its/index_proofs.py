#!/usr/bin/env python3
"""Generate the PDF's links to the exact theorem source lines; --check verifies them."""
import argparse
from pathlib import Path
import re

from verify import ROOT, MODULES, names


def collect():
    rows = {}
    for module in MODULES:
        source = (ROOT / "formal" / f"{module}.lean").read_text()
        for symbol in names(source):
            local = symbol.rsplit(".", 1)[-1]
            start = re.search(r"^(?:theorem|lemma)\s+" + re.escape(local) + r"\b", source, re.M)
            if not start:
                raise ValueError(symbol)
            rows[symbol] = (module, source.count("\n", 0, start.start()) + 1)
    return rows


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    rows = collect()
    sources = [ROOT / "technical-note.tex", *sorted((ROOT / "sections").glob("*.tex"))]
    for path in sources:
        for symbol in re.findall(r"\\proofat\{([\w.]+)\}", path.read_text()):
            if symbol not in rows:
                raise SystemExit(f"Unknown theorem {symbol} in {path.name}")
    commands = ["% Generated by index_proofs.py from the companion Lean sources."]
    for symbol, (module, line) in sorted(rows.items()):
        commands.append(r"\expandafter\def\csname ptgline:" + symbol
                        + r"\endcsname{" + module + r".lean\#L" + str(line) + "}")
    expected = "\n".join(commands) + "\n"
    path = ROOT / "formal" / "proof-lines.tex"
    if args.check:
        if path.read_text() != expected:
            raise SystemExit("Stale proof links: run python3 index_proofs.py")
    else:
        path.write_text(expected)


if __name__ == "__main__":
    main()
